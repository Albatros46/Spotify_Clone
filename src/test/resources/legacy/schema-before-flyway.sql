create table app_user (
    id bigint generated by default as identity primary key,
    name varchar(255) not null, email varchar(255) not null unique, password varchar(255) not null,
    role varchar(255) not null, refresh_token varchar(500),
    created_at timestamp(6) not null, updated_at timestamp(6) not null
);
create table song (
    id bigint generated by default as identity primary key,
    title varchar(255) not null, artist varchar(255) not null, album varchar(255) not null,
    song_url varchar(255) not null, image_url varchar(255) not null,
    created_at timestamp(6) not null, appuser_id bigint not null references app_user (id)
);
create table playlist (
    id bigint generated by default as identity primary key,
    name varchar(255) not null, description text, is_public boolean not null, image_url varchar(255),
    created_at timestamp(6) not null, updated_at timestamp(6) not null,
    appuser_id bigint not null references app_user (id)
);
create table playlist_song (
    id bigint generated by default as identity primary key,
    playlist_id bigint not null references playlist (id), song_id bigint not null references song (id),
    added_at timestamp(6) not null, position integer not null
);
