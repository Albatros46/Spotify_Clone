-- Initial schema (= what the entities of v1.0.0 describe). Runs on new, empty databases only;
-- databases created before Flyway are baselined at version 1 (spring.flyway.baseline-on-migrate).

create table app_user (
    id            bigint generated by default as identity primary key,
    name          varchar(255) not null,
    email         varchar(255) not null,
    password      varchar(255) not null,
    role          varchar(20)  not null check (role in ('USER', 'ADMIN')),
    refresh_token varchar(64),
    created_at    timestamp(6) not null,
    updated_at    timestamp(6) not null,
    constraint uk_app_user_email unique (email)
);

create table song (
    id         bigint generated by default as identity primary key,
    title      varchar(100) not null,
    artist     varchar(100) not null,
    album      varchar(100) not null,
    song_url   varchar(255) not null,
    image_url  varchar(255),
    created_at timestamp(6) not null,
    appuser_id bigint       not null,
    constraint fk_song_app_user foreign key (appuser_id) references app_user (id)
);

create table playlist (
    id          bigint generated by default as identity primary key,
    name        varchar(100) not null,
    description text,
    is_public   boolean      not null,
    image_url   varchar(255),
    created_at  timestamp(6) not null,
    updated_at  timestamp(6) not null,
    appuser_id  bigint       not null,
    constraint fk_playlist_app_user foreign key (appuser_id) references app_user (id)
);

create table playlist_song (
    id          bigint generated by default as identity primary key,
    playlist_id bigint       not null,
    song_id     bigint       not null,
    added_at    timestamp(6) not null,
    position    integer      not null,
    constraint fk_playlist_song_playlist foreign key (playlist_id) references playlist (id),
    constraint fk_playlist_song_song foreign key (song_id) references song (id),
    constraint uk_playlist_song unique (playlist_id, song_id)
);
